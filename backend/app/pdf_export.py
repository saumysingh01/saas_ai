"""
PDF export using PyMuPDF (fitz) v1.21+ Story API.

fitz.Story + DocumentWriter handles multi-page layout automatically:
- story.place(rect)  → flows as much content as fits, returns (more, filled)
- story.draw(dev)    → renders the placed content to the current page device
- Loops until more == 0 (all content placed).
"""

import io

import fitz  # PyMuPDF
import markdown as md_lib


_CSS = """
body {
    font-family: Arial, Helvetica, sans-serif;
    font-size: 11pt;
    color: #1a1a2e;
    line-height: 1.65;
}
h1 {
    font-size: 17pt;
    color: #4f46e5;
    border-bottom: 2px solid #4f46e5;
    padding-bottom: 5px;
    margin-bottom: 14px;
}
h2 {
    font-size: 12pt;
    color: #374151;
    margin-top: 18px;
    margin-bottom: 7px;
    padding-left: 7px;
    border-left: 3px solid #4f46e5;
}
h3 { font-size: 11pt; color: #4b5563; margin-top: 12px; }
p  { margin: 7px 0; }
strong { color: #111827; }
table {
    border-collapse: collapse;
    width: 100%;
    margin: 10px 0;
    font-size: 9.5pt;
}
td, th {
    border: 1px solid #d1d5db;
    padding: 5px 7px;
    text-align: left;
}
th {
    background-color: #eef2ff;
    font-weight: bold;
    color: #3730a3;
}
tr:nth-child(even) { background-color: #f9fafb; }
ul, ol { margin: 7px 0; padding-left: 18px; }
li { margin: 3px 0; }
code {
    background: #f3f4f6;
    padding: 1px 4px;
    border-radius: 3px;
    font-family: monospace;
    font-size: 9.5pt;
}
blockquote {
    border-left: 3px solid #4f46e5;
    margin: 7px 0;
    padding: 4px 10px;
    background: #f0f0ff;
    color: #4b5563;
}
"""

# A4 dimensions in points (1 pt = 1/72 inch)
_PAGE_W  = 595
_PAGE_H  = 842
_MARGIN  = 40
_MEDIABOX = fitz.Rect(0, 0, _PAGE_W, _PAGE_H)
_CONTENT_RECT = fitz.Rect(_MARGIN, _MARGIN, _PAGE_W - _MARGIN, _PAGE_H - _MARGIN)


def report_to_pdf_bytes(market_topic: str, report_markdown: str) -> bytes:
    """Convert a markdown market report to a styled, multi-page A4 PDF.

    Returns raw PDF bytes suitable for streaming as a file download.
    """
    html_body = md_lib.markdown(
        report_markdown,
        extensions=["tables", "fenced_code", "nl2br"],
    )

    # Escape market_topic for safe HTML embedding
    safe_topic = (
        market_topic
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

    full_html = f"""<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><style>{_CSS}</style></head>
<body>
<div style="background:#4f46e5;color:white;padding:7px 10px;font-size:9pt;border-radius:4px;margin-bottom:14px">
  <strong>MarketMind AI</strong> &nbsp;|&nbsp; {safe_topic}
</div>
{html_body}
<div style="margin-top:28px;padding-top:8px;border-top:1px solid #e5e7eb;font-size:8.5pt;color:#9ca3af;text-align:center">
  Generated by MarketMind AI &nbsp;&bull;&nbsp; Powered by CrewAI + Groq Llama
</div>
</body>
</html>"""

    # Write to an in-memory buffer using DocumentWriter.
    # Story.place() + Story.draw() loop handles pagination automatically.
    buf = io.BytesIO()
    writer = fitz.DocumentWriter(buf)
    story = fitz.Story(html=full_html, user_css=_CSS)

    more = True
    while more:
        dev = writer.begin_page(_MEDIABOX)
        more, _filled = story.place(_CONTENT_RECT)
        story.draw(dev)
        writer.end_page()

    writer.close()

    buf.seek(0)
    return buf.read()
